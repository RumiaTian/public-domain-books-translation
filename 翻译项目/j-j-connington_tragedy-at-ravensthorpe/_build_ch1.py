# ---- 覆盖完整性：块的行区间须恰好覆盖源文全部正文内容行 ----
expected = [i for i, l in enumerate(src_lines, 1) if l.strip() and i != 1]  # 跳过标题行 1
covered = []
for a, b, zh in BLOCKS:
    covered.extend(range(a, b + 1))
assert covered == expected, '行区间覆盖与源文内容行不一致'

# ---- 构建 ----
parts = ['## I / 第一章', '']
total_mirror = 0
for a, b, zh in BLOCKS:
    seg = src_lines[a - 1:b]
    while seg and not seg[0].strip():
        seg.pop(0)
    while seg and not seg[-1].strip():
        seg.pop()
    en_paras = [l for l in seg if l.strip()]
    assert len(en_paras) == len(zh), ('镜像段数不一致', a, b, len(en_paras), len(zh))
    for z in zh:
        assert '\ufeff' not in z and '\r' not in z and z == z.strip()
    total_mirror += len(zh)
    parts.append('===Original===')
    parts.append('\n'.join(seg))
    parts.append('')
    parts.append('===Chinese===')
    parts.append('\n\n'.join(zh))
    parts.append('')

text = '\n'.join(parts)
assert '\r' not in text
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_bytes(text.encode('utf-8'))

