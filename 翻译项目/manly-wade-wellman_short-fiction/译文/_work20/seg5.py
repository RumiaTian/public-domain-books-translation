out = []
pos = FSTART
def advance(target):
    global pos
    while pos < target:
        t = lines[pos-1].strip()
        assert t in ('---', ''), 'gap line %d not separator: %r' % (pos, lines[pos-1])
        if t == '---':
            out.append('---')
            out.append('')
        pos += 1

if TITLE:
    out.append(TITLE); out.append(''); pos = FSTART + 1

for s, e, ch in BLOCKS:
    advance(s)
    out.append('===Original===')
    out.append('\n'.join(lines[s-1:e]))
    out.append('')
    out.append('===Chinese===')
    out.append(ch.strip('\n'))
    out.append('')
    pos = e + 1
advance(FEND + 1)

