def main():
    start, end = int(sys.argv[1]), int(sys.argv[2])
    assert len(BLOCKS) == 57, 'unexpected block count: %d' % len(BLOCKS)
    assert set(T.keys()) == set(range(1, 57)), 'translation set incomplete'
    for i in range(start, end + 1):
        assert i in T
    chunks = []
    if start == 1 and not os.path.exists(OUT):
        chunks.append('## XXIV / 第二十四章\n\n')
    for i in range(start, end + 1):
        orig, ch = BLOCKS[i], T[i]
        sep = '\n' if (i == 56 and end == 56) else '\n\n'
        chunks.append('===Original===\n' + orig + '\n\n===Chinese===\n' + ch + sep)
    with open(OUT, 'a', encoding='utf-8', newline='\n') as f:
        f.write(''.join(chunks))
    data = open(OUT, encoding='utf-8').read()
    print('appended blocks %d-%d; file now: %d bytes, Original=%d Chinese=%d, FEFF=%d' % (
        start, end, len(data.encode('utf-8')), data.count('===Original==='),
        data.count('===Chinese==='), data.count('\ufeff')))


