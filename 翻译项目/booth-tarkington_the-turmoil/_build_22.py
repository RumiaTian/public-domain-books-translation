cn_n = t.count('===Chinese===')
print('block pairs:', orig_n, cn_n)
assert orig_n == cn_n == 16

# per-block paragraph count symmetry
import re
blocks = re.split(r'===Original===|===Chinese===', t)[1:]
for k in range(0, len(blocks), 2):
    eo = [p for p in blocks[k].split('\n\n') if p.strip()]
    ec = [p for p in blocks[k + 1].split('\n\n') if p.strip()]
    assert len(eo) == len(ec), ('asym', k // 2, len(eo), len(ec))

# Chinese block quote hygiene: no straight quotes, no corner brackets
cn_parts = re.split(r'===Original===|===Chinese===', t)[2::2]
cn_text = '\n'.join(cn_parts)
for bad in ['"', '\u300c', '\u300d']:
    n = cn_text.count(bad)
    print('chinese-block bad %r count: %d' % (bad, n))
oq, cq = cn_text.count('\u201c'), cn_text.count('\u201d')
osq, csq = cn_text.count('\u2018'), cn_text.count('\u2019')
print('curly double pairs: %d/%d  curly single pairs: %d/%d' % (oq, cq, osq, csq))
assert oq == cq and osq == csq
assert '"' not in cn_text and '\u300c' not in cn_text and '\u300d' not in cn_text

# paragraph totals
total_paras = sum(len([p for p in b.split('\n\n') if p.strip()]) for b in blocks[0::2])
print('total original paragraphs:', total_paras)
assert total_paras == 55

